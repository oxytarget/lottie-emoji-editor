export type ClientKey = keyof typeof dict;

export function ct(lang: Lang, key: ClientKey, vars: Record<string, string | number> = {}): string {
  return dict[key][lang].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export function useCT() {
  const lang = useEditor((s) => s.lang);
  return (key: ClientKey, vars?: Record<string, string | number>) => ct(lang, key, vars);
}

export const money = (usd: number) => `$${usd.toFixed(2)}`;

export function formatDate(lang: Lang, at: number): string {
  return new Date(at).toLocaleDateString(lang === 'uk' ? 'uk-UA' : lang === 'ru' ? 'ru-RU' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
}

export function formatDateTime(lang: Lang, at: number): string {
  return new Date(at).toLocaleString(lang === 'uk' ? 'uk-UA' : lang === 'ru' ? 'ru-RU' : 'en-GB', {
    day: 'numeric',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
  });
}
